def fib(n: int, count, cache) -> list:
    count[0] += 1

    if n in cache:
        return cache[n]
    
    if n < 2:
        return 1
    
    val = fib(n - 1, count, cache) + fib(n - 2, count, cache)
    cache[n] = val
    return val

