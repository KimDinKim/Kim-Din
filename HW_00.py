def fib_series(n: int) -> list:
    if n <= 0:
        return []
    elif n == 1:
        return [1]
    elif n == 2:
        return [1, 1]
    
    fib_list = [1, 1]
    
    for i in range(2, n):
        next_fib = fib_list[i - 1] + fib_list[i - 2]
        fib_list.append(next_fib)
        
    return fib_list

# Ввод числа n и вывод результата
n = int(input("Введите число n: "))
result = fib_series(n)
print(f"Числа Фибоначчи до {n}-го числа: {result}")



def sum_rev_fact(n: int) -> float:
    if n <= 0:
        return 0.0

    sum_rev_fact = 0.0
    factorial = 1  # Начинаем с 0! = 1

    for i in range(n):
        if i > 0:
            factorial *= i  # Вычисляем i! итеративно
        sum_rev_fact += 1 / factorial

    return sum_rev_fact

# Запрос числа n у пользователя
n = int(input("Введите число n: "))
result = sum_rev_fact(n)
print(f"Сумма обратных факториалов до {n-1}: {result}")


